-- Equipment Borrowing System: Supabase setup
-- Run this entire file in Supabase Dashboard > SQL Editor.
-- Safe for an existing project: creates missing tables and replaces only
-- the named policies/functions. Review duplicate asset codes before running.

create table if not exists public.equipment (
  id bigint generated by default as identity primary key,
  equipment_name text not null,
  category text not null,
  asset_code text not null,
  condition text default 'Good',
  availability text default 'Available',
  created_at timestamptz default now()
);

create table if not exists public.borrow_transactions (
  id bigint generated by default as identity primary key,
  equipment_id bigint not null references public.equipment(id),
  borrower_name text not null,
  borrower_type text not null,
  department text not null,
  date_borrowed date not null default current_date,
  due_date date not null,
  date_returned date,
  status text not null default 'Borrowed',
  user_id uuid references auth.users(id),
  created_at timestamptz default now()
);

-- Add missing columns for databases created from an earlier draft.
alter table public.equipment
  add column if not exists equipment_name text,
  add column if not exists category text,
  add column if not exists asset_code text,
  add column if not exists condition text default 'Good',
  add column if not exists availability text default 'Available',
  add column if not exists created_at timestamptz default now();

alter table public.borrow_transactions
  add column if not exists equipment_id bigint,
  add column if not exists borrower_name text,
  add column if not exists borrower_type text,
  add column if not exists department text,
  add column if not exists date_borrowed date default current_date,
  add column if not exists due_date date,
  add column if not exists date_returned date,
  add column if not exists status text default 'Borrowed',
  add column if not exists user_id uuid references auth.users(id),
  add column if not exists created_at timestamptz default now();

-- Enforce unique asset codes. This intentionally stops if duplicate codes exist;
-- fix those records first rather than silently changing or deleting data.
create unique index if not exists equipment_asset_code_unique
  on public.equipment (asset_code);

create index if not exists borrow_transactions_equipment_id_idx
  on public.borrow_transactions (equipment_id);
create index if not exists borrow_transactions_due_date_idx
  on public.borrow_transactions (due_date);
create index if not exists borrow_transactions_status_idx
  on public.borrow_transactions (status);


-- Add the expected foreign keys to older installations when they are absent.
do $
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'borrow_transactions_equipment_id_fkey'
      and conrelid = 'public.borrow_transactions'::regclass
  ) then
    alter table public.borrow_transactions
      add constraint borrow_transactions_equipment_id_fkey
      foreign key (equipment_id) references public.equipment(id);
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'borrow_transactions_user_id_fkey'
      and conrelid = 'public.borrow_transactions'::regclass
  ) then
    alter table public.borrow_transactions
      add constraint borrow_transactions_user_id_fkey
      foreign key (user_id) references auth.users(id);
  end if;
end $;

alter table public.equipment enable row level security;
alter table public.borrow_transactions enable row level security;

-- This exercise has one authenticated System User role.
drop policy if exists "Authenticated users manage equipment" on public.equipment;
create policy "Authenticated users manage equipment"
on public.equipment for all to authenticated
using (true) with check (true);

drop policy if exists "Authenticated users manage borrow transactions" on public.borrow_transactions;
create policy "Authenticated users manage borrow transactions"
on public.borrow_transactions for all to authenticated
using (true) with check (true);

-- Atomic borrowing: lock the equipment row, confirm availability, insert the
-- transaction and mark the equipment borrowed in one database transaction.
create or replace function public.borrow_equipment(
  p_equipment_id bigint,
  p_borrower_name text,
  p_borrower_type text,
  p_department text,
  p_date_borrowed date,
  p_due_date date
)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_equipment public.equipment%rowtype;
  v_transaction_id bigint;
begin
  if auth.uid() is null then
    raise exception 'You must be logged in to borrow equipment.';
  end if;
  if nullif(trim(p_borrower_name), '') is null then
    raise exception 'Borrower name is required.';
  end if;
  if nullif(trim(p_department), '') is null then
    raise exception 'Department is required.';
  end if;
  if p_date_borrowed is null or p_due_date is null or p_due_date < p_date_borrowed then
    raise exception 'Due date cannot be earlier than borrowing date.';
  end if;

  select * into v_equipment
  from public.equipment
  where id = p_equipment_id
  for update;

  if not found then
    raise exception 'Equipment record was not found.';
  end if;
  if v_equipment.availability <> 'Available' then
    raise exception 'This equipment is not available.';
  end if;

  insert into public.borrow_transactions (
    equipment_id, borrower_name, borrower_type, department,
    date_borrowed, due_date, status, user_id
  ) values (
    p_equipment_id, trim(p_borrower_name), p_borrower_type, trim(p_department),
    p_date_borrowed, p_due_date, 'Borrowed', auth.uid()
  ) returning id into v_transaction_id;

  update public.equipment
  set availability = 'Borrowed'
  where id = p_equipment_id;

  return v_transaction_id;
end;
$$;

-- Atomic return: prevent repeat returns and restore equipment availability.
create or replace function public.return_equipment(p_transaction_id bigint)
returns void
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_transaction public.borrow_transactions%rowtype;
begin
  if auth.uid() is null then
    raise exception 'You must be logged in to return equipment.';
  end if;

  select * into v_transaction
  from public.borrow_transactions
  where id = p_transaction_id
  for update;

  if not found then
    raise exception 'Borrowing transaction was not found.';
  end if;
  if v_transaction.status = 'Returned' then
    raise exception 'This transaction has already been returned.';
  end if;

  update public.borrow_transactions
  set status = 'Returned', date_returned = current_date
  where id = p_transaction_id;

  update public.equipment
  set availability = 'Available'
  where id = v_transaction.equipment_id;
end;
$$;

revoke all on function public.borrow_equipment(bigint, text, text, text, date, date) from public, anon;
revoke all on function public.return_equipment(bigint) from public, anon;
grant execute on function public.borrow_equipment(bigint, text, text, text, date, date) to authenticated;
grant execute on function public.return_equipment(bigint) to authenticated;
